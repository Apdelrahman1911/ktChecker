/** Bounds apply to unique selected roots, not once for every class sharing a JAR. */
internal data class CodeImageLimits(
    val maxRoots: Int = 128,
    val maxSelections: Int = 512,
    val maxEntries: Int = 50_000,
    val maxDepth: Int = 64,
    val maxEntryNameBytes: Int = 1024,
    val maxFileBytes: Long = 128L * 1024 * 1024,
    val maxRootBytes: Long = 192L * 1024 * 1024,
    val maxTotalBytes: Long = 256L * 1024 * 1024,
    val maxScanMillis: Long = 60_000,
) {
    init {
        require(maxRoots > 0 && maxSelections > 0 && maxEntries > 0 && maxDepth > 0 && maxEntryNameBytes > 0)
        require(maxFileBytes > 0 && maxRootBytes > 0 && maxTotalBytes > 0 && maxScanMillis in 1..3_600_000)
    }
}

/** Logical selectors and content only: no machine-local paths, timestamps or filesystem IDs. */
internal data class CodeImageRoot(
    val selectors: List<String>,
    val kind: String,
    val digest: String,
    val entryCount: Int,
    val byteCount: Long,
)

/**
 * Content identity of selected classes' actual protection-domain code sources and explicit resource
 * roots. A JAR is hashed in full; a directory includes every regular file and directory entry. Moving
 * an identical installation does not change its digest; renaming a directory entry does.
 *
 * Gradle commonly puts resources OUTSIDE its classes directory. Callers must select those resource
 * roots explicitly. This does not discover transitive classloaders, plugins, native/JDK libraries,
 * external resources or environment. A digest is neither execution authority nor qualification.
 *
 * The immutable capture retains identities, not copied executable bytes. verify() re-reads them;
 * there is deliberately no global path/class-name/mtime digest cache. Stable inventory/attribute
 * checks detect ordinary concurrent replacement, not adversarial restored writes. Installations
 * must be trusted and quiescent while captured/used. On-disk code-source identity cannot attest
 * already-loaded, transformed, instrumented or custom-classloader-generated bytecode in JVM memory.
 */
internal class CodeImage private constructor(
    val digest: String,
    val roots: List<CodeImageRoot>,
    private val selected: List<SelectedCodeRoot>,
    private val limits: CodeImageLimits,
) {
    /** Persistent byte/name/selection divergence or missing/unreadable inputs always fail closed. */
    fun verify() = codeImageBoundary {
        val current = CodeImageScanner(limits).scan(selected)
        if (current != roots || codeImageDigest(current) != digest) {
            codeImageFailure("code_image_changed", "Selected implementation or resource bytes changed after capture.")
        }
    }

    companion object {
        /**
         * Resolve the exact resource selected by the owner's real classloader, not a guessed source
         * directory. This selects the whole Gradle resource root or whole packed JAR for capture().
         * Only a canonical absolute resource name and an exactly matching file/JAR entry are accepted.
         * Version-remapped resource URLs are deliberately not guessed; select a supported root instead.
         */
        fun resourceRoot(owner: Class<*>, absoluteResource: String, limits: CodeImageLimits = CodeImageLimits()): Path = codeImageBoundary {
            val started = System.nanoTime()
            checkCodeClock(started, limits)
            if (!absoluteResource.startsWith('/') || absoluteResource.length > 4096) invalidResource()
            val name = absoluteResource.substring(1)
            val parts = name.split('/')
            if (parts.any { it in setOf("", ".", "..") || it.any { c -> c == '\\' || c.code < 32 || c.code == 127 } }) invalidResource()
            strictCodeUtf8(name)
            val resource = owner.getResource(absoluteResource)
                ?: codeImageFailure("code_image_resource_missing", "Selected implementation resource is unavailable.")
            checkCodeClock(started, limits)
            if (resource.ref != null || resource.query != null) invalidResource()
            when (resource.protocol) {
                "file" -> {
                    val file = Path.of(resource.toURI()).toAbsolutePath()
                    var root = file
                    for (part in parts.asReversed()) {
                        if (root.fileName?.toString() != part) invalidResource()
                        root = root.parent ?: invalidResource()
                    }
                    val canonical = resolveCodeRoot(root)
                    if (!stamp(canonical).directory) invalidResource()
                    val attributes = stamp(file)
                    requireReadable(file, attributes)
                    if (!attributes.regular) invalidResource()
                    if (attributes.size < 0 || attributes.size > limits.maxFileBytes) codeImageLimit()
                    if (file.toRealPath() != canonical.resolve(name)) {
                        codeImageFailure("code_image_symlink", "Selected resource redirects outside its exact resource root.")
                    }
                    checkCodeClock(started, limits)
                    root
                }
                "jar" -> {
                    val connection = resource.openConnection() as? JarURLConnection ?: invalidResource()
                    connection.useCaches = false
                    if (connection.entryName != name || connection.jarFileURL.protocol != "file" ||
                        connection.jarFileURL.ref != null || connection.jarFileURL.query != null) invalidResource()
                    val root = Path.of(connection.jarFileURL.toURI()).toAbsolutePath()
                    val canonical = resolveCodeRoot(root)
                    val before = stamp(canonical)
                    if (!before.regular) invalidResource()
                    if (before.size < 0 || before.size > limits.maxFileBytes || before.size > limits.maxRootBytes ||
                        before.size > limits.maxTotalBytes) codeImageLimit()
                    ZipFile(canonical.toFile()).use { archive ->
                        if (archive.size() > limits.maxEntries) codeImageLimit()
                        val entry = archive.getEntry(name) ?: invalidResource()
                        if (entry.isDirectory || entry.size < 0) invalidResource()
                        if (entry.size > limits.maxFileBytes) codeImageLimit()
                    }
                    if (stamp(canonical) != before) codeImageFailure("code_image_changed", "Selected resource archive changed during lookup.")
                    checkCodeClock(started, limits)
                    root
                }
                else -> codeImageFailure("code_image_resource_unsupported", "Selected resource has no supported local file or JAR identity.")
            }
        }

        fun capture(
            classes: Iterable<Class<*>>,
            additionalRoots: Map<String, Path> = emptyMap(),
            limits: CodeImageLimits = CodeImageLimits(),
        ): CodeImage = codeImageBoundary {
            val started = System.nanoTime()
            checkCodeClock(started, limits)
            val selections = linkedMapOf<Path, MutableCodeRoot>()
            val binaryNames = mutableMapOf<String, Class<*>>()
            var count = 0
            fun add(path: Path, selector: String, classEntry: String? = null) {
                checkCodeClock(started, limits)
                if (++count > limits.maxSelections) codeImageLimit()
                val original = path.toAbsolutePath()
                val canonical = resolveCodeRoot(original)
                val root = selections.getOrPut(canonical) {
                    if (selections.size >= limits.maxRoots) codeImageLimit()
                    MutableCodeRoot(canonical)
                }
                root.aliases.add(original)
                root.selectors += selector
                classEntry?.let { root.classEntries += it }
            }
            for (type in classes) {
                checkCodeClock(started, limits)
                if (type.isPrimitive || type.isArray || type.isHidden || type.name.length > 4096 ||
                    type.name.any { it == '/' || it == '\\' || it.code < 32 }) {
                    codeImageFailure("code_image_class_unsupported", "Selected class has no stable disk-backed binary identity.")
                }
                strictCodeUtf8(type.name)
                val previous = binaryNames.putIfAbsent(type.name, type)
                if (previous != null && previous !== type) {
                    codeImageFailure("code_image_class_ambiguous", "One binary name refers to multiple selected classloaders.")
                }
                // Count duplicate caller inputs as well, so an unbounded iterable cannot bypass bounds.
                val location = type.protectionDomain?.codeSource?.location
                    ?: codeImageFailure("code_image_source_unavailable", "Selected class has no observable code source.")
                if (location.protocol != "file") {
                    codeImageFailure("code_image_source_unsupported", "Selected code source is not a local file or directory.")
                }
                add(Path.of(location.toURI()), "class:${type.name}", type.name.replace('.', '/') + ".class")
            }
            for ((name, path) in additionalRoots) {
                if (!name.matches(Regex("[A-Za-z0-9][A-Za-z0-9_.:/+@-]{0,255}")) ||
                    name.split('/').any { it in setOf("", ".", "..") } || name.matches(Regex("[A-Za-z]:/.*"))) {
                    codeImageFailure("code_image_selector_invalid", "Explicit resource roots need bounded logical names, not paths.")
                }
                add(path, "resource:$name")
            }
            if (selections.isEmpty()) codeImageFailure("code_image_empty", "At least one actual code or explicit resource root is required.")
            val selected = frozenList(selections.values.map {
                SelectedCodeRoot(it.path, frozenList(it.aliases.toList()), frozenList(it.selectors.sorted()),
                    frozenList(it.classEntries.sorted()))
            })
            val roots = CodeImageScanner(limits, started).scan(selected)
            CodeImage(codeImageDigest(roots), roots, selected, limits)
        }
    }
}

private class MutableCodeRoot(val path: Path) {
    val aliases = linkedSetOf<Path>()
    val selectors = linkedSetOf<String>()
    val classEntries = linkedSetOf<String>()
}

private data class SelectedCodeRoot(
    val path: Path,
    val aliases: List<Path>,
    val selectors: List<String>,
    val classEntries: List<String>,
)

private data class CodeFileStamp(
    val directory: Boolean,
    val regular: Boolean,
    val symbolic: Boolean,
    val size: Long,
    val modified: FileTime,
    val created: FileTime,
    val key: Any?,
)

private fun BasicFileAttributes.codeStamp() = CodeFileStamp(isDirectory, isRegularFile, isSymbolicLink,
    size(), lastModifiedTime(), creationTime(), fileKey())

private data class CodeEntry(val name: String, val path: Path, val stamp: CodeFileStamp)
private data class CodeObservation(val selected: SelectedCodeRoot, val rootStamp: CodeFileStamp, val entries: List<CodeEntry>)

private class CodeImageScanner(private val limits: CodeImageLimits, private val started: Long = System.nanoTime()) {
    private var totalBytes = 0L
    private var totalEntries = 0
    private val buffer = ByteBuffer.allocate(65_536)

    fun scan(selected: List<SelectedCodeRoot>): List<CodeImageRoot> {
        val observations = mutableListOf<CodeObservation>()
        val roots = selected.map { root ->
            tick()
            verifyAliases(root)
            val before = stamp(root.path)
            requireReadable(root.path, before)
            val entries = if (before.directory) inventory(root.path, limits.maxEntries - totalEntries)
                else listOf(CodeEntry("", root.path, before))
            if (entries.size > limits.maxEntries - totalEntries) codeImageLimit()
            totalEntries += entries.size
            val names = entries.filter { it.stamp.regular }.mapTo(hashSetOf()) { it.name }
            if (before.directory && !names.containsAll(root.classEntries)) missingCodeClass()
            val framing = CodeFrames("ktchecker:code-directory:v1")
            framing.number(entries.size.toLong())
            var bytes = 0L
            var fileDigest: String? = null
            for (entry in entries) {
                tick()
                framing.text(entry.name)
                framing.text(if (entry.stamp.directory) "directory" else "file")
                if (entry.stamp.regular) {
                    val size = entry.stamp.size
                    if (size < 0 || size > limits.maxFileBytes || size > limits.maxRootBytes - bytes ||
                        size > limits.maxTotalBytes - totalBytes) codeImageLimit()
                    bytes += size
                    totalBytes += size
                    val digest = hashFile(entry)
                    framing.number(size)
                    framing.text(digest)
                    if (!before.directory) fileDigest = digest
                }
            }
            if (!before.directory && root.classEntries.isNotEmpty()) verifyArchiveClasses(root)
            val observation = CodeObservation(root, before, entries)
            verifyObservation(observation)
            observations += observation
            CodeImageRoot(root.selectors, if (before.directory) "directory" else "file",
                if (before.directory) framing.finish() else requireNotNull(fileDigest), entries.size, bytes)
        }
        // Detect ordinary changes to an earlier root while later roots were being hashed, too.
        observations.forEach(::verifyObservation)
        return frozenList(roots.sortedBy { it.selectors.joinToString("\u0000") })
    }

    private fun verifyAliases(root: SelectedCodeRoot) {
        root.aliases.forEach {
            tick()
            if (resolveCodeRoot(it) != root.path) {
                codeImageFailure("code_image_changed", "A selected code-source path now resolves to another root.")
            }
        }
    }

    private fun verifyObservation(observation: CodeObservation) {
        tick()
        verifyAliases(observation.selected)
        if (stamp(observation.selected.path) != observation.rootStamp ||
            (observation.rootStamp.directory && inventory(observation.selected.path, observation.entries.size) != observation.entries)) {
            codeImageFailure("code_image_changed", "Selected image inventory or attributes changed while being read.")
        }
    }

    private fun inventory(root: Path, allowed: Int): List<CodeEntry> {
        val entries = mutableListOf<CodeEntry>()
        fun visit(path: Path, attrs: BasicFileAttributes) {
            tick()
            val relative = root.relativize(path)
            if (relative.nameCount > limits.maxDepth || entries.size >= allowed) codeImageLimit()
            val name = relative.joinToString("/") { part ->
                val value = part.toString()
                if (value in setOf("", ".", "..") || value.any { it == '\\' || it.code < 32 || it.code == 127 } ||
                    part.fileSystem.getPath(value) != part) {
                    codeImageFailure("code_image_path_invalid", "Code image contains a nonportable or ambiguous entry name.")
                }
                value
            }
            val encoded = StandardCharsets.UTF_8.newEncoder().onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT).encode(java.nio.CharBuffer.wrap(name))
            if (encoded.remaining() > limits.maxEntryNameBytes) codeImageLimit()
            val stamp = attrs.codeStamp()
            requireReadable(path, stamp)
            // No entry may escape through a symlink/junction, including directory reparse points.
            if (path.toRealPath() != path.toAbsolutePath().normalize()) {
                codeImageFailure("code_image_symlink", "Code image entries must not redirect through symbolic links.")
            }
            entries += CodeEntry(name, path, stamp)
        }
        Files.walkFileTree(root, object : SimpleFileVisitor<Path>() {
            override fun preVisitDirectory(dir: Path, attrs: BasicFileAttributes): FileVisitResult {
                if (dir != root) visit(dir, attrs) else tick()
                return FileVisitResult.CONTINUE
            }
            override fun visitFile(file: Path, attrs: BasicFileAttributes): FileVisitResult {
                visit(file, attrs)
                return FileVisitResult.CONTINUE
            }
        })
        return entries.sortedBy { it.name }
    }

    private fun hashFile(entry: CodeEntry): String {
        if (stamp(entry.path) != entry.stamp) codeImageFailure("code_image_changed", "Selected file changed before hashing.")
        val digest = MessageDigest.getInstance("SHA-256")
        FileChannel.open(entry.path, READ, NOFOLLOW_LINKS).use { channel ->
            var remaining = entry.stamp.size
            while (remaining > 0) {
                tick()
                buffer.clear()
                buffer.limit(minOf(buffer.capacity().toLong(), remaining).toInt())
                val count = channel.read(buffer)
                if (count < 0) codeImageFailure("code_image_changed", "Selected file was truncated while hashing.")
                if (count > 0) {
                    digest.update(buffer.array(), 0, count)
                    remaining -= count
                }
            }
            buffer.clear().limit(1)
            if (channel.size() != entry.stamp.size || channel.read(buffer) != -1) {
                codeImageFailure("code_image_changed", "Selected file grew while hashing.")
            }
        }
        if (stamp(entry.path) != entry.stamp) codeImageFailure("code_image_changed", "Selected file changed while hashing.")
        return codeHex(digest.digest())
    }

    private fun verifyArchiveClasses(root: SelectedCodeRoot) {
        JarFile(root.path.toFile(), false, ZipFile.OPEN_READ, Runtime.version()).use { archive ->
            if (archive.size() > limits.maxEntries) codeImageLimit()
            root.classEntries.forEach { name ->
                tick()
                // This selects the runtime-versioned entry, including version-only package classes.
                val entry = archive.getJarEntry(name) ?: missingCodeClass()
                if (entry.isDirectory || entry.size < 0 || entry.size > limits.maxFileBytes) missingCodeClass()
            }
        }
    }

    private fun tick() {
        checkCodeClock(started, limits)
    }
}

private fun resolveCodeRoot(original: Path): Path {
    if (original.any { it.toString() in setOf(".", "..") }) {
        codeImageFailure("code_image_path_invalid", "Selected root paths must not contain dot or parent segments.")
    }
    if (Files.isSymbolicLink(original)) codeImageFailure("code_image_symlink", "Selected code-source roots must not be symbolic links.")
    if (!Files.exists(original, NOFOLLOW_LINKS)) {
        codeImageFailure("code_image_source_unavailable", "A selected code-source or resource root is missing.")
    }
    // Canonicalize trusted ancestor aliases (for example /var on macOS), then pin that target.
    val canonical = original.toRealPath()
    requireReadable(canonical, stamp(canonical))
    return canonical
}

private fun stamp(path: Path): CodeFileStamp = Files.readAttributes(path, BasicFileAttributes::class.java, NOFOLLOW_LINKS).codeStamp()

private fun requireReadable(path: Path, stamp: CodeFileStamp) {
    if (stamp.symbolic) codeImageFailure("code_image_symlink", "Selected code image contains a symbolic link.")
    if (!stamp.directory && !stamp.regular) {
        codeImageFailure("code_image_nonregular", "Selected code image contains an unsupported filesystem object.")
    }
    if (!Files.isReadable(path)) codeImageFailure("code_image_unreadable", "Selected code image is not readable.")
    Files.getFileAttributeView(path, PosixFileAttributeView::class.java, NOFOLLOW_LINKS)?.readAttributes()?.permissions()?.let { mode ->
        // Do not let a privileged test/developer process silently accept a mode-000 installation.
        val read = setOf(PosixFilePermission.OWNER_READ, PosixFilePermission.GROUP_READ, PosixFilePermission.OTHERS_READ)
        val search = setOf(PosixFilePermission.OWNER_EXECUTE, PosixFilePermission.GROUP_EXECUTE, PosixFilePermission.OTHERS_EXECUTE)
        if (mode.intersect(read).isEmpty() || (stamp.directory && mode.intersect(search).isEmpty())) {
            codeImageFailure("code_image_unreadable", "Selected code image denies readable/searchable filesystem access.")
        }
    }
}

private fun codeImageDigest(roots: List<CodeImageRoot>): String = CodeFrames("ktchecker:code-image:v1").apply {
    number(roots.size.toLong())
    for (root in roots) {
        number(root.selectors.size.toLong())
        root.selectors.forEach(::text)
        text(root.kind)
        text(root.digest)
        number(root.entryCount.toLong())
        number(root.byteCount)
    }
}.finish()

/** Length framing, not ambiguous path/newline concatenation. */
private class CodeFrames(domain: String) {
    private val digest = MessageDigest.getInstance("SHA-256")
    init { text(domain) }
    fun text(value: String) {
        val bytes = strictCodeUtf8(value)
        number(bytes.size.toLong())
        digest.update(bytes)
    }
    fun number(value: Long) { digest.update(ByteBuffer.allocate(java.lang.Long.BYTES).putLong(value).array()) }
    fun finish(): String = codeHex(digest.digest())
}

private fun codeHex(bytes: ByteArray): String = "sha256:" + HexFormat.of().formatHex(bytes)
private fun checkCodeClock(started: Long, limits: CodeImageLimits) {
    if (Thread.currentThread().isInterrupted) {
        codeImageFailure("code_image_interrupted", "Implementation identity capture was interrupted.")
    }
    if (System.nanoTime() - started > TimeUnit.MILLISECONDS.toNanos(limits.maxScanMillis)) codeImageLimit()
}
private fun strictCodeUtf8(value: String): ByteArray = try {
    val encoded = StandardCharsets.UTF_8.newEncoder().onMalformedInput(CodingErrorAction.REPORT)
        .onUnmappableCharacter(CodingErrorAction.REPORT).encode(java.nio.CharBuffer.wrap(value))
    ByteArray(encoded.remaining()).also { encoded.get(it) }
} catch (_: java.nio.charset.CharacterCodingException) {
    codeImageFailure("code_image_text_invalid", "Selected implementation identity contains malformed Unicode.")
}
private fun <T> frozenList(values: List<T>): List<T> = Collections.unmodifiableList(ArrayList(values))
private fun codeImageLimit(): Nothing = codeImageFailure("code_image_limit_exceeded", "Selected implementation image exceeds its configured identity-capture bounds.")
private fun missingCodeClass(): Nothing = codeImageFailure("code_image_class_missing", "Selected code source does not contain the required binary class entry.")
private fun invalidResource(): Nothing = codeImageFailure("code_image_resource_invalid", "Resource lookup did not identify the exact requested local entry and root.")
private fun codeImageFailure(code: String, message: String): Nothing = throw CliProblem(code, message)
private inline fun <T> codeImageBoundary(block: () -> T): T = try { block() } catch (failure: CliProblem) {
    throw failure
} catch (_: Exception) {
    // Never embed selected machine paths or raw filesystem/archive errors in a public identity error.
    codeImageFailure("code_image_read_failed", "Selected implementation identity could not be read and verified.")
}
